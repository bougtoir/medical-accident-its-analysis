# 4. DISCUSSION
# ══════════════════════════════════════════════════════════════════
add_heading_styled("4. Discussion", level=1)
add_para_with_refs(
    "Our central finding is narrow and, we believe, defensible: the "
    "mean-bias\u2013plus\u2013limits-of-agreement summary that dominates "
    "device-validation reporting can miss a clinically relevant gain error "
    "when a coincidental offset cancels its effect on the mean, whereas the "
    "Bland\u2013Altman difference-versus-mean regression " +
    C.cite("blandaltman1999") + ", Deming " + C.cite("linnet1990") +
    " and Passing\u2013Bablok " + C.cite("passingbablok1983") + " regression, "
    "and the CCC scale shift " + C.cite("lin2000") + " all detect it. This is "
    "a critique of common reporting practice, not of the Bland\u2013Altman "
    "method itself.")

add_heading_styled("4.1. Recommendations for validation reporting", level=2)
add_para_with_refs(
    "Validation studies of arterial pressure and derived monitors " +
    C.cite("kim2014", "joosten2017") + " should therefore report, in addition "
    "to mean bias and limits of agreement: (i) the Bland\u2013Altman regression "
    "slope with its CI (or, equivalently, a Deming or Passing\u2013Bablok "
    "slope); (ii) the CCC with its decomposition into r, C_b, u and v; and "
    "(iii) the sampled pressure range, because the CCC is range-dependent " +
    C.cite("nickerson1997", "barnhart2007") + ". Notably, C_b alone is "
    f"relatively insensitive to a pure gain error (in S4, C_b was "
    f"{f3(st['S4_gain_masked']['C_b'])} despite v = "
    f"{f3(st['S4_gain_masked']['v'])}); the scale shift v should be reported "
    "explicitly. These additions cost nothing beyond a few lines of analysis "
    "and would let regulators and clinicians " + C.cite("odor2017") +
    " distinguish offset-corrected agreement from genuine gain accuracy.")

add_heading_styled("4.2. Dynamic response is a distinct, clinical gain error", level=2)
add_para_with_refs(
    "The dynamic-response error is specific to fluid-filled systems and is "
    "routinely encountered at the bedside as under-damping (air bubbles, long "
    "compliant tubing) or over-damping (clots, kinks) " +
    C.cite("gardner1981", "romagnoli2014") + ". Because it is "
    "frequency-dependent, it is not fully captured by static "
    "method-comparison statistics and is best assessed directly with the "
    "fast-flush test, from which f_n and \u03b6 are read " +
    C.cite("kleinman1992") + ". We therefore recommend that a fast-flush "
    "dynamic-response check accompany any accuracy statement for a "
    "fluid-filled arterial line; pulse pressure is the sensitive readout, "
    "because it is proportional to gain but independent of offset.")

add_heading_styled("4.3. Implications for sensor design", level=2)
add_para_with_refs(
    "The reason zeroing is still performed today is that it corrects a "
    "setup-specific offset in real time, a role that no retrospective "
    "method-comparison statistic can fill. This also points to the way "
    "forward: because zeroing addresses only the operational offset problem, "
    "designing the offset sources out of the hardware removes the need to zero "
    "at all, leaving gain and dynamic response as the residual design and "
    "validation problems.")
add_para_with_refs(
    "The offset that zeroing corrects can also be removed by design. "
    "Catheter-tip micro-electro-mechanical systems (MEMS) sensors abolish the "
    "hydrostatic column " + C.cite("hasenkamp2012", "song2020") + "; absolute "
    "sensors with barometric compensation remove the atmospheric reference; "
    "and self-calibrating MEMS references limit drift " + C.cite("kang2022") +
    ". High-fidelity pressure wires already demonstrate accurate catheter-based "
    "pressure measurement " + C.cite("scalia2023") + ". With offset removed by "
    "design and gain verified by accurate PP reproduction, the residual "
    "systematic error is expressed entirely in v, giving a concrete design "
    "target (v \u2248 1, C_b \u2265 0.99 without calibration) " +
    C.cite("mcbride2005") + ". Modern piezoresistive MEMS sensors achieve "
    "non-linearity well below 0.1% of full scale " + C.cite("barlian2009") +
    ", supporting the assumption that gain verified over the pulsatile range "
    "generalises across the physiological range.")

add_heading_styled("4.4. Extension to derived haemodynamic monitors", level=2)
add_para_with_refs(
    "The offset-versus-gain distinction extends to derived monitors whose "
    "auto-calibration routines re-optimise a setpoint (an offset correction) "
    "without correcting the gain of the pressure- or "
    "impedance-to-flow conversion " +
    C.cite("chatterjee2009", "ameloot2015", "squara2007", "manecke2005") +
    ". Reporting the scale shift v for these devices would make their "
    "dependence on calibration explicit.")

add_heading_styled("4.5. Limitations", level=2)
add_para_with_refs(
    "This is a simulation study; the data are synthetic and chosen to isolate "
    "specific error structures, and they are not a substitute for a "
    "prospective clinical comparison against an invasive reference of stated "
    "precision " + C.cite("cecconi2009") + ". The static model assumes "
    "sensor linearity, and the dynamic model is a single second-order "
    "approximation. The value of the work is to make explicit, and "
    "reproducibly quantify, which reported analyses detect a residual gain "
    "error, a prelude to rather than a replacement for empirical validation.")

