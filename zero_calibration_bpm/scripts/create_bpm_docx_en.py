    rf"pressure ($PP = \mathrm{{SBP}} - \mathrm{{DBP}}$) is a pure AC "
    "quantity and is therefore independent of any additive DC offset but "
    rf"proportional to sensor gain (see Figure {next_fig_num()}, which "
