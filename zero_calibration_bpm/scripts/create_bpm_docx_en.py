# MOVE TABLES INLINE (insert at [TABLE N] placeholders)
# ══════════════════════════════════════════════════════════════════
def move_tables_inline():
    """Move each table, its caption and its footnote to the placeholder in the body."""
    placeholders = {}
    headings = {}
    captions = {}
    footnotes = {}
    for p in doc.paragraphs:
        t = p.text.strip()
        if t.startswith("[TABLE ") and t.endswith("]"):
            placeholders[t] = p
        elif t in ("Table 1", "Table 2", "Table 3"):
            headings[t] = p
        elif t.startswith(("Table 1.", "Table 2.", "Table 3.")):
            captions[t.split(".")[0]] = p
        elif t.startswith("BA = ") or t.startswith("PP ratio = "):
            footnotes[t] = p
    for idx, table in enumerate(doc.tables, start=1):
        marker = f"[TABLE {idx}]"
        table_key = f"Table {idx}"
        ph = placeholders.get(marker)
        cap = captions.get(table_key)
        if not ph or not cap:
            continue
        if table_key in headings:
            ph._p.addprevious(headings[table_key]._p)
        ph._p.addprevious(cap._p)
        ph._p.addnext(table._tbl)
        # attach the matching footnote (first footnote for Table 1/3; PP for Table 2)
        if table_key in ("Table 1", "Table 3"):
            fn = next((f for txt, f in footnotes.items() if txt.startswith("BA = ")), None)
        else:
            fn = next((f for txt, f in footnotes.items() if txt.startswith("PP ratio = ")), None)
        if fn:
            table._tbl.addnext(fn._p)
            footnotes.pop(fn.text.strip(), None)
        ph._element.getparent().remove(ph._element)

