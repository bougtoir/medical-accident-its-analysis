add_heading_styled("2.2. Statistical methods", level=2)
add_para_with_refs(
    "For each paired dataset we computed: (i) the minimal Bland\u2013Altman "
    "summary, comprising mean bias, 95% limits of agreement (mean bias \u00b1 1.96 SD) "
    "and percentage error " + C.cite("critchley1999") + "; (ii) the "
    "Bland\u2013Altman regression of the differences on the mean, whose slope "
    "tests for proportional bias " + C.cite("blandaltman1999") + "; (iii) "
    "Deming regression, which allows for error in both methods, with "
    "jackknife confidence intervals " + C.cite("linnet1990") + "; (iv) "
    "Passing\u2013Bablok non-parametric regression " +
    C.cite("passingbablok1983") + "; and (v) Lin\u2019s CCC " +
    C.cite("lin1989") + ".")

add_para_with_refs(
    "Lin\u2019s CCC (\u03c1c) decomposes as \u03c1c = r \u00d7 C_b, where r is "
    "Pearson\u2019s correlation (precision) and C_b is the bias-correction "
    "factor (accuracy) " + C.cite("lin2000") + ". C_b further decomposes as:")
add_eq(r"C_b = 2 / (v + 1/v + u^2)")
add_para_with_refs(
    rf"where $v = \sigma_{{\mathrm{{device}}}} / \sigma_{{\mathrm{{reference}}}}$ "
    rf"is the scale shift (the gain ratio) and "
    rf"$u = (\mu_{{\mathrm{{device}}}} - \mu_{{\mathrm{{reference}}}}) / "
    rf"\sqrt{{\sigma_{{\mathrm{{device}}}} \sigma_{{\mathrm{{reference}}}}}}$ "
    "is the location shift (offset). Zeroing drives $u$ toward zero but leaves "
    rf"$v$ unchanged; a residual gain error keeps $v \neq 1$ even after perfect zeroing.")

add_para_with_refs(
    rf"We used fixed a-priori detection rules, reported here so they cannot be "
    rf"chosen post hoc: the mean-bias summary flags an error if $|\mathrm{{mean\ bias}}| > "
    rf"{f1(P['bias_threshold'])}$ mmHg; the Bland-Altman regression flags if "
    "the slope 95% confidence interval (CI) excludes 0; Deming and "
    "Passing-Bablok flag if the slope 95% CI excludes 1; and the CCC "
    rf"scale shift flags if $|v - 1| > {f2(P['v_threshold'])}$. Strength of "
    "agreement was interpreted using published CCC criteria " +
    C.cite("mcbride2005") + ".")

add_heading_styled("2.3. Dynamic response and the fast-flush test", level=2)
add_para_with_refs(
    rf"The fluid-filled catheter-transducer system behaves as a second-order "
    rf"system characterised by a natural frequency $f_n$ and a damping "
    rf"coefficient $\zeta$ " + C.cite("gardner1981") + ". We modelled its "
    rf"transfer function $H(f) = 1 / [1 - (f/f_n)^2 + i \cdot 2\zeta(f/f_n)]$ "
    "and applied it to the Fourier harmonics of synthetic arterial waveforms. "
    rf"Under-damping (low $\zeta$, resonance near the arterial harmonics) causes "
    "systolic overshoot and $PP$ over-estimation; over-damping attenuates $PP$. "
    "Both are gain errors on the pulsatile signal that zeroing cannot correct, "
    "and both are quantified at the bedside by the fast-flush (square-wave) "
    "test " + C.cite("kleinman1992", "romagnoli2014") + ".")

