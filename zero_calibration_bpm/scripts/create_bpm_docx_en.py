def latex_to_omml(latex, display=False):
    """Return a Word OMML element for a LaTeX expression via pandoc."""
    wrap = f"$${latex}$$" if display else f"${latex}$"
    with tempfile.TemporaryDirectory() as td:
        md_path = os.path.join(td, "eq.md")
        docx_path = os.path.join(td, "eq.docx")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(wrap)
        subprocess.run(["pandoc", md_path, "-o", docx_path],
                       check=True, stdout=subprocess.DEVNULL)
        with zipfile.ZipFile(docx_path) as z:
            xml = z.read("word/document.xml")
    tree = etree.fromstring(xml)
    ns = {"m": "http://schemas.openxmlformats.org/officeDocument/2006/math"}
    omath = tree.xpath(".//m:oMath", namespaces=ns)[0]
    return etree.fromstring(etree.tostring(omath))


def add_math_run(p, latex, font_size=Pt(12)):
    run = p.add_run()
    run.font.name = "Cambria Math"
    run.font.size = font_size
    run._r.append(latex_to_omml(latex))
    return run


def add_eq(latex):
    p = doc.add_paragraph()
