def compile_stores():
    stores = []
    for name, date_str, pref, city in RAW_STORES:
        year = int(date_str.split(".")[0])
        month = int(date_str.split(".")[1])
        day = int(date_str.split(".")[2])
        stores.append({
            "store_name": name,
            "open_date": date_str,
            "open_year": year,
            "open_month": month,
            "prefecture": pref,
            "city": city,
        })

    # Summary
    print(f"Total Round1 Japan stores compiled: {len(stores)}")
    print(f"Opening year range: {min(s['open_year'] for s in stores)}"
          f" – {max(s['open_year'] for s in stores)}")

    # Prefecture counts
    pref_counts = {}
    for s in stores:
        pref_counts[s["prefecture"]] = pref_counts.get(s["prefecture"], 0) + 1
    print(f"\nPrefectures with Round1: {len(pref_counts)}")
    for pref, cnt in sorted(pref_counts.items(), key=lambda x: -x[1]):
        print(f"  {pref}: {cnt} stores")

    # Save
    json_path = os.path.join(DATA_DIR, "round1_japan_stores.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(stores, f, ensure_ascii=False, indent=2)
    print(f"\nSaved JSON: {json_path}")

    csv_path = os.path.join(DATA_DIR, "round1_japan_stores.csv")
    with open(csv_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=stores[0].keys())
        writer.writeheader()
        writer.writerows(stores)
    print(f"Saved CSV: {csv_path}")

    return stores


if __name__ == "__main__":
    compile_stores()
