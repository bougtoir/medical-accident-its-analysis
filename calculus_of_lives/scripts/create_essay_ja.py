def _jp(run):
    run.font.name = JP_FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), JP_FONT)


def build():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = JP_FONT
    st.font.size = Pt(11)
    st._element.rPr.rFonts.set(qn("w:eastAsia"), JP_FONT)
    st.paragraph_format.line_spacing = 1.9

    for s in doc.sections:
        s.top_margin = s.bottom_margin = Inches(1)
        s.left_margin = s.right_margin = Inches(1)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(TITLE); r.bold = True; r.font.size = Pt(15); _jp(r)

    sp = doc.add_paragraph()
    sp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sr = sp.add_run(SUBTITLE); sr.italic = True; sr.font.size = Pt(10.5)
    sp.paragraph_format.space_after = Pt(12)

    for style, text in BODY:
        if style == "H":
            hp = doc.add_paragraph()
            hp.paragraph_format.space_before = Pt(10)
            hp.paragraph_format.space_after = Pt(4)
            hr = hp.add_run(text); hr.bold = True; hr.font.size = Pt(12.5); _jp(hr)
        else:
            pp = doc.add_paragraph()
            pp.paragraph_format.first_line_indent = Pt(11)
            rr = pp.add_run(text); _jp(rr)

    doc.save(OUT / "essay_ja.docx")
    chars = sum(len(t) for s, t in BODY if s == "P")
    print("essay_ja.docx written to", OUT, "| approx JP chars:", chars)


if __name__ == "__main__":
    build()
