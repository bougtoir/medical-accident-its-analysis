CAPACITY_FILE = DATA_DIR / "05sisetu05.xlsx"

# Population in 2023 (used to convert counts to per-100k rates).
POPULATION_2023 = 124_351_000

# Share of the total national exam volume assumed to be available for new
# cancer workups generated by a DTC screening wave. This is a scenario
# assumption; the base value is the same as the original model.
AVAILABLE_CANCER_SHARE = 0.20

