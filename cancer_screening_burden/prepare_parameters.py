CHILD_TEEN_COLS = ["0-4 yrs.", "5-9 yrs.", "10-14 yrs.", "15-19 yrs."]
ADULT_COLS = [c for c in AGE_COLS if c not in CHILD_TEEN_COLS]


def load_pop(sex: str, year: int = 2023) -> pd.Series:
    pop = pd.read_excel(POP_FILE, sheet_name="pop", header=0)
    row = pop[
        (pop["Population"] == "All (including foreigners)")
        & (pop["Sex"] == sex)
        & (pop["Calendar year"] == year)
    ].iloc[0]
    return row


def load_incidence_rate(sex: str, site: str, year: int = 2023) -> pd.Series:
    rate = pd.read_excel(POP_FILE, sheet_name="rate", header=0)
    sub = rate[
        (rate["Year at diagnosis"] == year) & (rate["Sex"] == sex) & (rate["Site"] == site)
    ]
    if sub.empty:
        raise ValueError(f"No incidence rate found for {sex=}, {site=}, {year=}")
    return sub.iloc[0]


def per100k_total(count: float) -> float:
    """Convert an absolute count to cases per 100,000 total Japanese population."""
    return count / POPULATION_2023 * 100_000.0


def adult_incidence_per100k_total(sex: str, site: str) -> float:
    """Compute adult (20+) incidence per 100,000 total population.

    This is used as a conservative proxy for the point prevalence of
    screen-detectable cancers in the DTC-screened cohort.
    """
    pop_row = load_pop(sex)
    rate_row = load_incidence_rate(sex, site)
    adult_cases = 0.0
    for col in ADULT_COLS:
        rate = rate_row[col]
        if pd.isna(rate) or rate == "-":
            continue
        adult_cases += float(rate) * float(pop_row[col]) / 100_000.0
    return per100k_total(adult_cases)


def compute_age_specific_incidence(sex: str, site: str) -> pd.DataFrame:
    """Return a DataFrame with age-group incidence rates (per 100k in that age group)."""
    pop_row = load_pop(sex)
    rate_row = load_incidence_rate(sex, site)
    rows = []
    for col in AGE_COLS:
        rate = rate_row[col]
        if pd.isna(rate) or rate == "-":
            continue
        rows.append({"age_group": col, "incidence_per_100k": float(rate)})
    return pd.DataFrame(rows)


def compute_capacity() -> Dict[str, float]:
    """Compute annual diagnostic exam counts per 100k from MHLW facility survey.

    The survey reports one-month patient counts for September 2023. Annualising with
    *12 gives a total national volume; we then apply AVAILABLE_CANCER_SHARE to reflect
    the portion that can be reallocated to cancer workups from a single DTC wave.
    """
    xl = pd.ExcelFile(CAPACITY_FILE)
    hosp = xl.parse("表11", header=None)
    clinic = xl.parse("表12", header=None)

    def monthly_patients(df: pd.DataFrame, codes: List[str]) -> float:
        total = 0.0
        for code in codes:
            row = df[df[2].astype(str).str.strip() == code]
            if row.empty:
                continue
            val = row.iloc[0, 9]
            try:
                total += float(val)
            except Exception:
                pass
        return total

    ct_monthly = monthly_patients(hosp, ["13", "14", "15", "16", "17"]) + monthly_patients(
        clinic, ["13", "14", "15", "16", "17"]
    )
    mri_monthly = monthly_patients(hosp, ["18", "19", "20"]) + monthly_patients(
        clinic, ["18", "19", "20"]
    )
    gastro_monthly = monthly_patients(hosp, ["03"]) + monthly_patients(clinic, ["03"])
    colon_monthly = monthly_patients(hosp, ["04"]) + monthly_patients(clinic, ["04"])
    endoscopy_monthly = gastro_monthly + colon_monthly

    def per100k_annual(monthly: float) -> float:
        return monthly * 12 / POPULATION_2023 * 100_000.0 * AVAILABLE_CANCER_SHARE

    return {
        "ct_exams_per_year": per100k_annual(ct_monthly),
        "mri_exams_per_year": per100k_annual(mri_monthly),
        "endoscopy_exams_per_year": per100k_annual(endoscopy_monthly),
        # Specialist capacity is not directly reported by the facility survey;
        # retained as an illustrative scenario value.
        "specialist_visits_per_year": 8_000.0,
    }


